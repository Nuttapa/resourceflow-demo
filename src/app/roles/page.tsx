'use client';

import { useMemo } from 'react';
import { PageHeader } from '@/components/ui/PageHeader';
import { Card, CardBody, CardHeader } from '@/components/ui/Card';
import { Badge } from '@/components/ui/Badge';
import { ConditionalCases, PermissionMatrixTable } from '@/components/domain/PermissionMatrix';
import { buildPermissionMatrix } from '@/lib/matrix';
import { ROLE_LABEL } from '@/lib/types';
import { useDemoState } from '@/state/DemoStateProvider';

export default function RolesPage() {
  const { state, activeUser, hydrated } = useDemoState();
  const matrix = useMemo(() => buildPermissionMatrix(state), [state]);

  return (
    <>
      <PageHeader
        title="Roles & Permissions"
        description="This table is generated by calling the application's own permission function for every role — it is not a hand-written summary that could drift from the code."
      />

      <Card className="mb-4">
        <CardBody>
          <p className="text-sm">
            You are acting as <span className="font-medium">{activeUser.name}</span> —{' '}
            <Badge tone="accent">{ROLE_LABEL[activeUser.role]}</Badge>
          </p>
          <p className="mt-2 text-sm text-muted">
            The role selector is a <span className="font-medium text-fg">simulated demo session</span>, not
            authentication. There is no password, no token and no identity provider anywhere in this
            application, and every check below runs in the browser. These are frontend-only demonstration
            rules — they are not production security, and a real system would enforce the same matrix on a
            server.
          </p>
        </CardBody>
      </Card>

      <Card>
        <CardHeader
          title="Permission matrix"
          description="Each cell is a live call to can(role, action, context). Rows marked Conditional depend on who owns the record."
        />
        {hydrated ? (
          <PermissionMatrixTable matrix={matrix} />
        ) : (
          <div className="space-y-2 p-5" aria-busy="true" aria-live="polite">
            <span className="sr-only">Evaluating the permission rules</span>
            {[0, 1, 2, 3].map((i) => (
              <div key={i} className="h-11 animate-pulse rounded-lg bg-elevated" />
            ))}
          </div>
        )}
      </Card>

      <Card className="mt-4">
        <CardHeader
          title="Conditional rules, evaluated separately"
          description="A single fixture cannot describe a rule that depends on ownership, so these cases are evaluated on their own."
        />
        <CardBody>
          {hydrated ? (
            <ConditionalCases matrix={matrix} />
          ) : (
            <div className="space-y-2" aria-busy="true">
              <span className="sr-only">Evaluating the permission rules</span>
              {[0, 1].map((i) => (
                <div key={i} className="h-16 animate-pulse rounded-lg bg-elevated" />
              ))}
            </div>
          )}
        </CardBody>
      </Card>

      <Card className="mt-4">
        <CardHeader title="What the table does not say" description="Permission is only the first gate." />
        <CardBody>
          <ul className="space-y-2 text-sm text-muted">
            <li>
              <span className="font-medium text-fg">Status still applies.</span> Every action also checks the
              workflow state machine. An Approver may decide a request in principle, yet be refused because the
              request is already rejected.
            </li>
            <li>
              <span className="font-medium text-fg">Capacity still applies.</span> An Administrator may allocate
              resources, but the allocation is refused when the pool has no room.
            </li>
            <li>
              <span className="font-medium text-fg">Order of checks.</span> The workflow tests existence, then
              status, then permission, then capacity — so the reason you get back is the first thing that
              actually blocked the action.
            </li>
            <li>
              <span className="font-medium text-fg">Refusals are recorded.</span> Every blocked attempt is
              written to the demo audit trail with the actor and the reason, without changing any data.
            </li>
          </ul>
        </CardBody>
      </Card>
    </>
  );
}
