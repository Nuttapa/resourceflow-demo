'use client';

import { Badge } from '@/components/ui/Badge';
import { ROLE_LABEL } from '@/lib/types';
import type { MatrixCell, PermissionMatrix as Matrix } from '@/lib/matrix';

function Verdict({ cell }: { cell: MatrixCell }) {
  // Never colour alone: each cell carries a word and an icon as well.
  return cell.allowed ? (
    <span className="inline-flex items-center gap-1.5 text-success">
      <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="3" aria-hidden="true">
        <path d="M20 6 9 17l-5-5" />
      </svg>
      <span className="text-sm font-medium">Allowed</span>
    </span>
  ) : (
    <span className="inline-flex items-center gap-1.5 text-danger" title={cell.reason}>
      <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="3" aria-hidden="true">
        <path d="M6 6l12 12M18 6L6 18" />
      </svg>
      <span className="text-sm font-medium">Refused</span>
    </span>
  );
}

export function PermissionMatrixTable({ matrix }: { matrix: Matrix }) {
  return (
    <div className="overflow-x-auto">
      <table className="w-full min-w-[46rem] border-collapse text-sm">
        <caption className="sr-only">
          Permission matrix generated by calling the application&apos;s own permission rules
        </caption>
        <thead>
          <tr className="border-b border-line text-left">
            <th scope="col" className="px-5 py-2.5 text-xs font-medium uppercase tracking-wide text-muted">
              Action
            </th>
            {matrix.personas.map((persona) => (
              <th
                key={persona.id}
                scope="col"
                className="px-5 py-2.5 text-xs font-medium uppercase tracking-wide text-muted"
              >
                {ROLE_LABEL[persona.role]}
                <span className="block font-normal normal-case text-muted/80">{persona.name}</span>
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {matrix.rows.map((row) => (
            <tr key={row.action} className="border-b border-line/70 last:border-0 align-top">
              <th scope="row" className="px-5 py-3 text-left font-normal">
                <span className="block font-medium">{row.label}</span>
                <span className="block font-mono text-xs text-muted">{row.action}</span>
                {row.conditional ? (
                  <span className="mt-1.5 block">
                    <Badge tone="info">Conditional</Badge>
                    <span className="mt-1 block text-xs text-muted">Evaluated against {row.fixture}.</span>
                  </span>
                ) : null}
              </th>
              {row.cells.map((cell) => (
                <td key={`${row.action}-${cell.role}`} className="px-5 py-3">
                  <Verdict cell={cell} />
                  {!cell.allowed && cell.reason ? (
                    <span className="mt-1 block text-xs text-muted">{cell.reason}</span>
                  ) : null}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

export function ConditionalCases({ matrix }: { matrix: Matrix }) {
  return (
    <ul className="space-y-5">
      {matrix.conditionals.map((item) => (
        <li key={item.id}>
          <p className="text-sm font-medium">{item.label}</p>
          <p className="mt-1 text-sm text-muted">{item.description}</p>
          <ul className="mt-2 flex flex-wrap gap-x-6 gap-y-2">
            {item.cells.map((cell) => (
              <li key={`${item.id}-${cell.role}`} className="text-sm">
                <span className="text-muted">{ROLE_LABEL[cell.role]}: </span>
                <Verdict cell={cell} />
              </li>
            ))}
          </ul>
        </li>
      ))}
    </ul>
  );
}
